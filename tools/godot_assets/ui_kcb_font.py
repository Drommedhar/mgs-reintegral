"""Decode font.res using font/font.c's layout without embedding glyph artwork."""

import struct

from .formats import span

FONT_ID = "ca68.r"
NATIVE_GLYPH_BASE = 0xF0000
DASH_CODE = 0xF4000
CELL = (20, 16)
COLUMNS = 32


def font_glyphs(data: bytes) -> dict:
    table_end, bank_start = struct.unpack(">2I", span(data, 0, 8))
    if table_end != 8 + 96 * 4 or not table_end <= bank_start <= len(data):
        raise ValueError("Invalid KCB font table extent")
    padding = (-bank_start) % 4
    bank_size = len(data) - bank_start - padding
    if len(data) % 4 or bank_size % 36 or not 0 < bank_size // 36 < 4096:
        raise ValueError("Invalid KCB font bank extent")
    if padding and data[-padding:] != bytes(padding):
        raise ValueError("Invalid KCB font alignment padding")
    result = {}
    for index, (descriptor,) in enumerate(
        struct.iter_unpack(">I", span(data, 8, table_end - 8))
    ):
        width, offset_y = (descriptor >> 24) & 15, descriptor >> 28
        start = table_end + (descriptor & 0xFFFFFF)
        if not 0 < width <= 12 or offset_y > 2 or start + width * 3 > bank_start:
            raise ValueError("Invalid KCB half-width glyph")
        result[32 + index] = (width, offset_y, span(data, start, width * 3))
    for index in range(bank_size // 36):
        result[NATIVE_GLYPH_BASE + index + 1] = (
            12,
            1,
            span(data, bank_start + index * 36, 36),
        )
    # Native #- is generated by put_hankaku_4bpp rather than stored in font.res.
    result[DASH_CODE] = (18, 0, b"\0" * 22 + b"\x0f" + b"\xff" * 4 + b"\0" * 27)
    return result


def subtitle_palette() -> tuple[bytes, ...]:
    # menu_jimaku_init: font_set_color(kcb, 0, 0x6739, 0).
    return tuple(
        bytes((level * 255 // 31,) * 3 + (255 if level else 0,))
        for level in (0, 25 // 3, 50 // 3, 25)
    )


def kcb_font(data: bytes, texture: str) -> tuple[dict, bytes]:
    glyphs = font_glyphs(data)
    width = COLUMNS * CELL[0]
    height = ((len(glyphs) + COLUMNS - 1) // COLUMNS) * CELL[1]
    image = bytearray(width * height * 4)
    palette = subtitle_palette()
    metrics = {}
    for index, (code, (glyph_width, offset_y, packed)) in enumerate(glyphs.items()):
        x, y = (index % COLUMNS) * CELL[0] + 1, (index // COLUMNS) * CELL[1] + 1
        metrics[str(code)] = {
            "rect": [x, y, glyph_width, 12],
            "advance": glyph_width,
            "offset": 0,
            "offset_y": offset_y,
        }
        for pixel in range(glyph_width * 12):
            coverage = (packed[pixel // 4] >> (6 - (pixel % 4) * 2)) & 3
            dest = ((y + pixel // glyph_width) * width + x + pixel % glyph_width) * 4
            image[dest : dest + 4] = palette[coverage]
    return {
        "schema": 1,
        "format": "kcb",
        "texture": texture,
        "size": [width, height],
        "font_size": 12,
        "height": 12,
        "line_height": 18,
        "bank_length": len(glyphs) - 97,
        "glyphs": metrics,
    }, bytes(image)
